export function getDomainsMetrics(): DomainsMetricData {
  const total = mockDomains.length;
  const primary = mockDomains.filter((d) => d.isPrimary).length;
  const pending = mockDomains.filter((d) => d.verificationStatus !== "active").length;
  const sslExpiring = mockDomains.filter((d) => d.ssl.remainingDays > 0 && d.ssl.remainingDays <= 30).length;
  const healthy = mockDomains.filter((d) => d.health.status === "healthy").length;
  const failed = mockDomains.filter((d) => d.status === "failed").length;
  const avgLatency = Math.round(
    mockDomains.filter((d) => d.health.latency > 0).reduce((s, d) => s + d.health.latency, 0) /
    mockDomains.filter((d) => d.health.latency > 0).length,
  );
  return {
    totalDomains: total,
    primaryDomains: primary,
    pendingVerification: pending,
    sslExpiringSoon: sslExpiring,
    healthyDomains: healthy,
    failedDomains: failed,
    averageResponseTime: avgLatency || 0,
  };
}
