export function getPlansMetrics() {
  const total = mockPlans.length;
  const active = mockPlans.filter((p) => p.status === "active").length;
  const trial = mockPlans.filter((p) => p.trialEnabled).length;
  const featured = mockPlans.filter((p) => p.recommended).length;
  const avgPrice = Math.round(mockPlans.reduce((sum, p) => sum + p.monthlyPrice, 0) / total);
  const unlimited = mockPlans.filter(
    (p) => p.limits.students === null || p.limits.courses === null,
  ).length;
  return { totalPlans: total, activePlans: active, trialPlans: trial, featuredPlans: featured, averageMonthlyPrice: avgPrice, unlimitedPlans: unlimited };
}
