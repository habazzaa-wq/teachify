export function getTenantUsersMetrics(): TenantUserMetricData {
  const users = mockTenantUsers;
  const now = new Date();
  const firstDayOfMonth = new Date(now.getFullYear(), now.getMonth(), 1);

  return {
    totalUsers: users.length,
    activeUsers: users.filter((u) => u.status === "active").length,
    inactiveUsers: users.filter((u) => u.status === "inactive").length,
    suspendedUsers: users.filter((u) => u.status === "suspended").length,
    twoFactorEnabled: users.filter((u) => u.twoFactorEnabled).length,
    newThisMonth: users.filter((u) => new Date(u.createdAt) >= firstDayOfMonth).length,
    departmentCount: new Set(users.map((u) => u.department)).size,
    pendingInvites: 0,
  };
}
