/**
 * Generates the shared country/currency lists used by the web form and the API.
 * Source: https://github.com/mledoze/countries (ISO 3166-1 + ISO 4217).
 *
 * Usage: node scripts/generate-country-data.mjs
 */
import { writeFile } from "node:fs/promises";

const SOURCE = "https://raw.githubusercontent.com/mledoze/countries/master/countries.json";

// Keep the Saudi code used by the existing Fawaterk integration.
const CURRENCY_OVERRIDES = { SA: "SR" };

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`Failed to fetch countries: ${response.status}`);
const source = await response.json();

const countries = source
  .filter((item) => /^[A-Z]{2}$/.test(item.cca2 ?? "") && item.currencies && Object.keys(item.currencies).length > 0)
  .map((item) => {
    const currency = CURRENCY_OVERRIDES[item.cca2] ?? Object.keys(item.currencies)[0];
    return {
      code: item.cca2,
      nameAr: item.translations?.ara?.common ?? item.name?.common ?? item.cca2,
      nameEn: item.name?.common ?? item.cca2,
      currency,
    };
  })
  .sort((a, b) => a.nameAr.localeCompare(b.nameAr, "ar"));

if (countries.length < 190) throw new Error(`Unexpected country count: ${countries.length}`);

const tsLines = countries.map((country) => {
  const nameAr = country.nameAr.replace(/'/g, "\\'");
  const nameEn = country.nameEn.replace(/'/g, "\\'");
  return `  { code: "${country.code}", nameAr: "${nameAr}", nameEn: "${nameEn}", currency: "${country.currency}" },`;
});

const ts = `/**
 * ISO 3166-1 country list with default ISO 4217 currency.
 * Generated by scripts/generate-country-data.mjs — do not edit by hand.
 */
export interface CountryOption {
  code: string;
  nameAr: string;
  nameEn: string;
  currency: string;
}

export const COUNTRY_OPTIONS: CountryOption[] = [
${tsLines.join("\n")}
];

// "SR" is kept for prices saved by the legacy Saudi pricing form.
export const CURRENCY_CODES: string[] = [...new Set([...COUNTRY_OPTIONS.map((country) => country.currency), "SR"])].sort();

const COUNTRY_BY_CODE = new Map(COUNTRY_OPTIONS.map((country) => [country.code, country]));

/** Default currency for a country code (falls back to EGP for unknown codes). */
export function defaultCurrencyForCountry(code: string): string {
  return COUNTRY_BY_CODE.get(code.toUpperCase())?.currency ?? "EGP";
}

/** Arabic label for a country code (falls back to the raw code). */
export function countryNameForCode(code: string): string {
  return COUNTRY_BY_CODE.get(code.toUpperCase())?.nameAr ?? code;
}
`;

const phpLines = countries.map((country) => {
  const name = country.nameAr.replace(/'/g, "\\'");
  return `        '${country.code}' => ['name' => '${name}', 'currency' => '${country.currency}'],`;
});

const php = `<?php

declare(strict_types=1);

namespace App\\Support;

/**
 * ISO 3166-1 country list with default ISO 4217 currency.
 * Generated by scripts/generate-country-data.mjs — do not edit by hand.
 */
final class CountryData
{
    /** @var array<string, array{name: string, currency: string}> */
    public const COUNTRIES = [
${phpLines.join("\n")}
    ];

    public static function name(string $countryCode): string
    {
        return self::COUNTRIES[strtoupper($countryCode)]['name'] ?? $countryCode;
    }

    public static function currency(string $countryCode): string
    {
        return self::COUNTRIES[strtoupper($countryCode)]['currency'] ?? 'EGP';
    }
}
`;

await writeFile(new URL("../apps/web/src/constants/countries.ts", import.meta.url), ts, "utf8");
await writeFile(new URL("../apps/api/app/Support/CountryData.php", import.meta.url), php, "utf8");

console.log(`Generated ${countries.length} countries for web and API.`);
